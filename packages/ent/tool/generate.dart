// Writes test/support/library.g.dart from lib/ent.dart, read with package:analyzer: the public top-level names, the
// top-level constants, the classes that only hold constants, and the classes' public methods, static methods and
// setters by name with each class's superclass, as Dart the tests compile against. The tests use it where they once
// read the library through dart:mirrors; test/generated_test.dart fails while the file is not what this writes. Run
// from packages/ent: dart run tool/generate.dart

import 'dart:io';

import 'package:analyzer/dart/analysis/analysis_context_collection.dart';
import 'package:analyzer/dart/analysis/results.dart';
import 'package:analyzer/dart/element/element.dart';
import 'package:analyzer/dart/element/nullability_suffix.dart';
import 'package:analyzer/dart/element/type.dart';
import 'package:analyzer/dart/element/type_provider.dart';
import 'package:dart_style/dart_style.dart';

/// Where the generated file lives, from the package root.
const output = 'test/support/library.g.dart';

void main() async {
  File(output).writeAsStringSync(await generate());
}

/// The generated file's text, formatted as dart format writes it.
Future<String> generate() async {
  final path = File('lib/ent.dart').absolute.path;
  final library = ((await AnalysisContextCollection(
    includedPaths: [path],
  ).contextFor(path).currentSession.getResolvedLibrary(path)) as ResolvedLibraryResult).element;
  final elements = library.exportNamespace.definedNames2;
  final names = [
    for (final name in elements.keys)
      if (!name.endsWith('=') && !name.startsWith('_')) name,
  ]..sort();
  final classes = [
    for (final name in names)
      if (elements[name] case final ClassElement type) type,
  ];

  return DartFormatter(languageVersion: DartFormatter.latestLanguageVersion, pageWidth: 120).format(
    (StringBuffer()
          ..writeln('// Generated by tool/generate.dart from lib/ent.dart; test/generated_test.dart checks that it is')
          ..writeln('// current. Do not edit: run dart run tool/generate.dart.')
          ..writeln()
          ..writeln("// The library's deprecated members are called by name like the others.")
          ..writeln('// ignore_for_file: deprecated_member_use_from_same_package')
          ..writeln()
          ..writeln("import 'dart:typed_data';")
          ..writeln()
          ..writeln("import 'package:ent/ent.dart';")
          ..writeln()
          ..writeln('/// The public top-level names of the library, sorted.')
          ..writeln('const List<String> publicNames = [${names.map((name) => "'$name'").join(', ')}];')
          ..writeln()
          ..writeln('/// The top-level constants, by name.')
          ..write('const Map<String, Object?> constants = {')
          ..writeAll([
            for (final name in names)
              if (elements[name] case GetterElement(variable: TopLevelVariableElement(isConst: true))) "'$name': $name",
          ], ', ')
          ..writeln('};')
          ..writeln()
          ..writeln('/// The classes that only hold static constants, by name, each with its constants by name.')
          ..write('const Map<String, Map<String, Object?>> constantClasses = {')
          ..writeAll([
            for (final type in classes)
              if (_constantsOnly(type))
                "'${type.name}': {${_fields(type).map((field) => "'$field': ${type.name}.$field").join(', ')}}",
          ], ', ')
          ..writeln('};')
          ..writeln()
          ..writeln(
            "/// Each public class's own public instance methods, by class and name, as tear-offs from an instance.",
          )
          ..write('final Map<String, Map<String, Function Function(Object)>> methods = {')
          ..writeAll(classes.map(_methods), ', ')
          ..writeln('};')
          ..writeln()
          ..writeln("/// Each public class's public static methods, by class and name.")
          ..write('final Map<String, Map<String, Function>> statics = {')
          ..writeAll(classes.map(_statics), ', ')
          ..writeln('};')
          ..writeln()
          ..writeln("/// Each public class's own public instance setters, by class and name.")
          ..write('final Map<String, Map<String, void Function(Object, Object?)>> setters = {')
          ..writeAll(classes.map((type) => _setters(type, library.typeProvider)), ', ')
          ..writeln('};')
          ..writeln()
          ..writeln('/// The superclass of every class of the library, private ones included, by name.')
          ..write('const Map<String, String> superclasses = {')
          ..writeAll([
            for (final type in library.classes)
              if (type.supertype case final supertype? when !supertype.isDartCoreObject)
                "'${type.name}': '${supertype.element.name}'",
          ], ', ')
          ..writeln('};'))
        .toString(),
  );
}

// The map entry of [type]'s own public instance methods.
String _methods(ClassElement type) {
  return _entry(type, [
    for (final method in type.methods)
      if (_named(method) && !method.isStatic) "'${method.name}': (o) => (o as ${_type(type)}).${method.name}",
  ]);
}

// The map entry of [type]'s public static methods.
String _statics(ClassElement type) {
  return _entry(type, [
    for (final method in type.methods)
      if (_named(method) && method.isStatic) "'${method.name}': ${type.name}.${method.name}",
  ]);
}

// The map entry of [type]'s own public instance setters, each casting its value to the setter's type (with dynamic
// for the class's type parameters).
String _setters(ClassElement type, TypeProvider types) {
  final instance = type.instantiate(
    typeArguments: List.filled(type.typeParameters.length, types.dynamicType),
    nullabilitySuffix: NullabilitySuffix.none,
  );

  return _entry(type, [
    for (final setter in type.setters)
      if (_named(setter) && !setter.isStatic)
        "'${setter.name}': (o, v) => (o as ${_type(type)}).${setter.name} = "
            "${_cast(instance.getSetter(setter.name!)!.formalParameters.first.type)}",
  ]);
}

// The setter value `v` as [type] takes it: cast, unless any value is accepted.
String _cast(DartType type) {
  if (type is DynamicType) {
    return 'v';
  }

  if (type.isDartCoreObject && type.nullabilitySuffix == NullabilitySuffix.question) {
    return 'v';
  }

  return 'v as ${type.getDisplayString()}';
}

// A map entry of [type]'s [members], each written as `'name': value`.
String _entry(ClassElement type, List<String> members) => "'${type.name}': {${members.join(', ')}}";

// Whether [element] is public and named like a member, not an operator.
bool _named(Element element) => element.isPublic && RegExp(r'^[A-Za-z]\w*$').hasMatch(element.name ?? '');

// [type] as code: generic classes with dynamic type arguments, as strict-raw-types asks.
String _type(ClassElement type) {
  if (type.typeParameters.isEmpty) {
    return type.name!;
  }

  return '${type.name}<${List.filled(type.typeParameters.length, 'dynamic').join(', ')}>';
}

// The names of the fields [type] declares itself.
List<String> _fields(ClassElement type) {
  return [
    for (final field in type.fields)
      if (field.isOriginDeclaration) field.name!,
  ];
}

// Whether [type] declares static constants and nothing else, as MOUSE and TOUCH do.
bool _constantsOnly(ClassElement type) {
  if (_fields(type).isEmpty) {
    return false;
  }

  if (type.methods.isNotEmpty) {
    return false;
  }

  return type.fields.where((field) => field.isOriginDeclaration).every((field) => field.isStatic && field.isConst);
}
