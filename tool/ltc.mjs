// Generates packages/ent_flutter/lib/src/gpu/ltc_data.dart from r187's
// examples/jsm/lights/RectAreaLightTexturesLib.js: the LTC_MAT_1 and LTC_MAT_2 arrays (64 × 64 RGBA texels each),
// converted with r187's DataUtils.toHalfFloat and stored as base64 of little-endian half floats, as
// RectAreaLightTexturesLib's LTC_HALF_1 and LTC_HALF_2 hold them (the iPhone 11's A13 cannot filter float32
// textures linearly, so the LTC_FLOAT tables are not used).
// Run from the repository root: node tool/ltc.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { toHalfFloat } from '../third_party/three.js/src/extras/DataUtils.js';

const source = readFileSync('third_party/three.js/examples/jsm/lights/RectAreaLightTexturesLib.js', 'utf8');
const lines = [
	'// Generated by tool/ltc.mjs from the reference\'s RectAreaLightTexturesLib (LTC_MAT_1, LTC_MAT_2: 64 × 64 RGBA',
	'// texels each, base64 of little-endian half floats from DataUtils.toHalfFloat). Do not edit.',
	'',
];

for (const n of [1, 2]) {
	const match = source.match(new RegExp(`const LTC_MAT_${n} = (\\[[^\\]]*\\]);`));
	const values = JSON.parse(match[1].replace(/- /g, '-'));

	if (values.length !== 64 * 64 * 4) {
		throw new Error(`LTC_MAT_${n}: ${values.length} values`);
	}

	const text = Buffer.from(new Uint16Array(values.map(toHalfFloat)).buffer).toString('base64');
	lines.push(`const String ltc${n} =`);

	for (let i = 0; i < text.length; i += 100) {
		lines.push(`    '${text.slice(i, i + 100)}'${i + 100 >= text.length ? ';' : ''}`);
	}

	lines.push('');
}

writeFileSync('packages/ent_flutter/lib/src/gpu/ltc_data.dart', lines.join('\n'));
